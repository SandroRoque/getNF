#!/usr/bin/env python3
"""Writes a Supabase migration that loads taxonomy/categories.txt, descriptions-en.txt and tags.txt into the seed tables
(taxonomy_node, taxonomy_tag), then brings every user's categories up to it (sync_taxonomy_for, D70).

Run after editing the taxonomy:  python3 tools/taxonomy-sql.py  (writes supabase/migrations/<now>_taxonomy.sql)
Comments in the files are never copied: they name real items.
"""
import datetime, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def q(text):
  return "'" + text.replace("'", "''") + "'"


def nodes():
  stack, order, out = [], {}, []
  for raw in open(os.path.join(ROOT, "taxonomy", "categories.txt"), encoding="utf-8"):
    line = raw.split("#", 1)[0].rstrip()
    if not line.strip():
      continue
    depth = (len(line) - len(line.lstrip(" "))) // 2
    slug, label = line.strip().split(None, 1)
    stack[depth:] = [slug]
    parent = ".".join(stack[:-1]) or None
    order[parent] = order.get(parent, 0) + 1
    out.append((".".join(stack), label.strip(), parent, order[parent]))
  return out


def descriptions():
  out = {}
  for raw in open(os.path.join(ROOT, "taxonomy", "descriptions-en.txt"), encoding="utf-8"):
    if raw.strip() and not raw.startswith("#"):
      path, text = raw.rstrip("\n").split("\t", 1)
      out[path] = text.strip()
  return out


def tags():
  out = []
  for raw in open(os.path.join(ROOT, "taxonomy", "tags.txt"), encoding="utf-8"):
    line = raw.split("#", 1)[0].strip()
    if line:
      slug, description = line.split(None, 1)
      out.append((slug, description.strip()))
  return out


def main():
  rows = nodes()
  described = descriptions()
  sql = ["-- Generated by tools/taxonomy-sql.py from taxonomy/*.txt. Don't edit; regenerate.", ""]
  # Parents before children (file order guarantees it), so the self-reference holds on insert.
  sql.append("insert into public.taxonomy_node (path, label, parent_path, sort, description_en) values")
  sql.append(",\n".join(f"  ({q(p)}, {q(l)}, {q(pp) if pp else 'null'}, {s}, {q(described[p]) if p in described else 'null'})"
                         for p, l, pp, s in rows))
  sql.append("on conflict (path) do update set label = excluded.label, parent_path = excluded.parent_path, sort = excluded.sort,")
  sql.append("  description_en = excluded.description_en;")
  sql.append("")
  sql.append("insert into public.taxonomy_tag (slug, description) values")
  sql.append(",\n".join(f"  ({q(s)}, {q(d)})" for s, d in tags()))
  sql.append("on conflict (slug) do update set description = excluded.description;")
  sql.append("")
  sql.append("select public.sync_taxonomy_for(id) from auth.users;")
  stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d%H%M%S")
  path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "supabase", "migrations", f"{stamp}_taxonomy.sql")
  open(path, "w", encoding="utf-8").write("\n".join(sql) + "\n")
  print(f"{len(rows)} categories -> {path}")


if __name__ == "__main__":
  main()
